class PromptBuilder:
    LESSON_RUNTIME_RULES = [
        "Учитывай текущий прогресс и незавершённое с прошлого урока.",
        "Обычный урок опирай прежде всего на основной учебник курса.",
        "Сформулируй цель и измеримый предметный результат.",
        "Свяжи результат с реальной деятельностью учащихся.",
        "Планируй реалистичный тайминг.",
        "Предусмотри актуализацию, объяснение, практику и контроль понимания.",
        "Отдельно укажи, что записать в тетрадь.",
        "Используй содержательную рефлексию.",
        "Домашнее задание давай только с понятной функцией.",
        "Не утверждай, что урок проведён: результат является планом.",
    ]

    def build_lesson_prompt(
        self,
        user_request: str,
        class_context: dict,
        retrieved_sources: list[dict],
    ) -> str:
        rules = "\n".join(f"- {rule}" for rule in self.LESSON_RUNTIME_RULES)
        return f"""
ROLE
Ты — профессиональный ассистент учителя истории и обществознания.

TASK
{user_request}

CLASS CONTEXT
{class_context}

SOURCE CONTEXT
{retrieved_sources}

RUNTIME SOP
{rules}

OUTPUT
Создай готовый к проведению сценарий урока. Не выдумывай отсутствующие
цитаты, страницы, факты о прошлом уроке или источниках.
""".strip()
