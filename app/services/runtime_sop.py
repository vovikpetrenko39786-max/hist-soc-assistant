    def _subject_rules(self, subject: str) -> list[str]:
        code = (subject or "").upper()
        if code == "HISTORY":
            return list(self.HISTORY)
        if code == "SOCIAL_STUDIES":
            return list(self.SOCIAL_STUDIES)
        return []

    def rules(self, artifact_type: str, subject: str, mode: str) -> list[str]:
        mapping = {
            "lesson": self.LESSON_COMMON,
            "assessment": self.ASSESSMENT_COMMON,
            "worksheet": self.WORKSHEET_COMMON,
            "homework": self.HOMEWORK_COMMON,
            "idea_enhancement": self.IDEA_COMMON,
        }
        rules = list(mapping.get(artifact_type, []))
        rules += self._subject_rules(subject)
        rules += self.MODES.get(mode, self.MODES["practical"])
        return rules

    def lesson_rules(self, subject: str, mode: str) -> list[str]:
        return self.rules("lesson", subject, mode)
